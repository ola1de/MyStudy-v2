#!/usr/bin/env python3
"""Generate apps/web/src/data/content.ts from the real MyStudy data repos.

Counts are computed from the repos and the verified import/fix reports —
nothing is typed by hand, so the homepage can never show invented numbers.
Run: python3 tools/generate-content-data.py
Sources:
  - tools/import-questions/out/report.json (11,267 imported exam questions)
  - docs/fixes-24-nov/placeholders-filled-24-nov.md totals (8,580 practice)
  - data-repos/mystudy-textbooks (273 chapters, 1,482 modules, 13,650 quiz)
  - data-repos/vocabulary-database/index.json (44 categories, 4,400 words)
"""
import json
import pathlib
import re

HOME = pathlib.Path.home() / "workspace" / "mystudy"
DATA = HOME / "data-repos"

rep = json.load(open(HOME / "tools" / "import-questions" / "out" / "report.json"))
by_exam = rep["by_exam"]  # JAMB 5235, NECO 2744, WAEC 2728, PRI 560

SUBJECT_NAMES = {
    "Accounting": "Financial Accounting", "Agric": "Agricultural Science",
    "Biology": "Biology", "CRS": "Christian Religious Studies",
    "Chemistry": "Chemistry", "Civic": "Civic Education",
    "Commerce": "Commerce", "Computer": "Computer Studies",
    "Economics": "Economics", "English": "English Language",
    "FurtherMath": "Further Mathematics", "Geography": "Geography",
    "Government": "Government", "Hausa": "Hausa", "History": "History",
    "IRS": "Islamic Religious Studies", "Igbo": "Igbo",
    "Literature": "Literature in English", "Mathematics": "Mathematics",
    "Physics": "Physics", "Yoruba": "Yoruba",
}
exam_dir = DATA / "Exam-Questions-Data" / "json"
subjects = sorted({re.sub(r"^(JAMB|WAEC|NECO)_", "", f.stem).rsplit("_", 1)[0]
                   for f in exam_dir.glob("JAMB_*.json")})
assert len(subjects) == 21, subjects
by_subject = {s: rep["by_subject"].get(s, 0) for s in subjects}

# Keypoints: chapter counts per subject folder (mathematics has an index file).
DISPLAY_SUBJECT = {
    "accounting": "Financial Accounting", "agric": "Agricultural Science",
    "biology": "Biology", "chemistry": "Chemistry", "civic": "Civic Education",
    "commerce": "Commerce", "computer": "Computer Studies",
    "crs": "Christian Religious Studies", "economics": "Economics",
    "english": "English Language", "further-maths": "Further Mathematics",
    "geography": "Geography", "government": "Government", "hausa": "Hausa",
    "history": "History", "igbo": "Igbo", "irs": "Islamic Religious Studies",
    "literature": "Literature in English", "mathematics": "Mathematics",
    "physics": "Physics", "yoruba": "Yoruba",
}
kp_subjects = []
for folder in sorted((DATA / "mystudy-textbooks").iterdir()):
    if not folder.is_dir() or folder.name.startswith("."):
        continue
    files = [f for f in folder.glob("*.json") if "index" not in f.name]
    kp_subjects.append({"slug": folder.name,
                        "name": DISPLAY_SUBJECT[folder.name],
                        "chapters": len(files)})
total_chapters = sum(s["chapters"] for s in kp_subjects)
assert total_chapters == 273, total_chapters

vocab = json.load(open(DATA / "vocabulary-database" / "index.json"))
vocab_cats = [{"slug": c["slug"], "name": c["title"], "count": c["count"]}
              for c in vocab["categories"]]
assert len(vocab_cats) == 44, len(vocab_cats)

ts = """// GENERATED by tools/generate-content-data.py — do not edit by hand.
// Every number below was counted from the data repos and the verified
// import/fix reports. Practice sets are syllabus-modelled, labelled
// practice:true, and are never presented as verbatim official papers.

export const EXAM_SUBJECTS: { slug: string; name: string; questions: number }[] = %s;

export const EXAM_QUESTIONS = { jamb: %d, waec: %d, neco: %d, primary: %d, total: %d, withExplanations: %d };

export const PRACTICE_QUESTIONS = { jamb: 900, waec: 4240, neco: 3440, total: 8580 };

export const KEYPOINTS = { chapters: 273, modules: 1482, quiz: 13650, subjects: %s };

export const VOCABULARY = { categories: 44, words: 4400, quiz: 4400, list: %s };
""" % (
    json.dumps([{"slug": s, "name": SUBJECT_NAMES[s], "questions": by_subject[s]}
                for s in subjects], indent=2),
    by_exam["JAMB"], by_exam["WAEC"], by_exam["NECO"], by_exam["PRI"],
    rep["questions_total"], rep["questions_with_explanations"],
    json.dumps(kp_subjects),
    json.dumps(vocab_cats),
)
out = HOME / "apps" / "web" / "src" / "data" / "content.ts"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(ts)
print(f"wrote {out} ({len(ts)} bytes)")
print(f"exam total {rep['questions_total']}, subjects {len(subjects)}, "
      f"keypoint chapters {total_chapters}, vocab categories {len(vocab_cats)}")
