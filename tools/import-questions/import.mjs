// MyStudy v2 — question importer (Phase 1).
// Reads /tmp/mystudy-repos/Exam-Questions-Data/json/*.json and normalises
// the 3 schemas in the repo audit (docs/repo-audit-24-nov.md §2.5) to one
// canonical shape, writing a D1 seed SQL file + a report.
//
// Rules (do not weaken):
// - NEVER invent questions, explanations, or topics. `topic` stays NULL
//   until a human (or a syllabus-based authoring pass) assigns it.
// - Skip the 190 placeholder files (1-question files whose question is
//   "Question Content Here?") — they are listed in the report, not imported.
// - Skip the 11 corrupt files (JSON parse failure) — listed in the report.
// - Dedup by content hash within (exam, subject, year). The same question
//   appearing in a different year is a different row, not a duplicate.
// - Metadata (exam, subject, year) comes from the filename only — the
//   files carry no metadata fields.
// - Question-bank rule (user, 24 Nov 2026): placeholder files are filled
//   in a SEPARATE syllabus-modelled authoring task, labelled
//   practice:true and never presented as verbatim official papers.
//   This importer does NOT do that filling.
//
// Usage: node tools/import-questions/import.mjs
//   [--source /tmp/mystudy-repos/Exam-Questions-Data/json]
//   [--out tools/import-questions/out]

import { createHash } from 'node:crypto';
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, '..', '..');
const args = process.argv.slice(2);
const getArg = (name, fallback) => {
  const i = args.indexOf(name);
  return i >= 0 && args[i + 1] ? args[i + 1] : fallback;
};
const sourceDir = getArg('--source', '/tmp/mystudy-repos/Exam-Questions-Data/json');
const outDir = getArg('--out', join(here, 'out'));

const PLACEHOLDER_Q = 'Question Content Here?';

function sqlStr(value) {
  if (value === null || value === undefined) return 'NULL';
  return `'${String(value).replace(/'/g, "''")}'`;
}

function contentHash(q) {
  return createHash('sha256')
    .update([q.exam, q.subject, q.year, q.question, q.options.join('||')].join('|'))
    .digest('hex');
}

function normalise(entry, ctx) {
  // Schema B — passage block: expand inner questions, keep the passage.
  if (entry && entry.type === 'passage' && Array.isArray(entry.questions)) {
    return entry.questions
      .map((inner) => normalise({ ...inner, passage: entry.content }, ctx))
      .flat();
  }
  // Schema A (type 'std') and Schema C (no type, may carry `explanation`).
  if (!entry || typeof entry.q !== 'string' || !Array.isArray(entry.opts)) return [];
  if (entry.opts.length !== 4) return [{ invalid: true, reason: `expected 4 options, got ${entry.opts.length}` }];
  if (!Number.isInteger(entry.ans) || entry.ans < 0 || entry.ans > 3) {
    return [{ invalid: true, reason: `answer index out of range: ${entry.ans}` }];
  }
  return [
    {
      exam: ctx.exam,
      subject: ctx.subject,
      year: ctx.year,
      topic: null,
      type: entry.passage ? 'passage' : 'std',
      question: entry.q,
      options: entry.opts.map(String),
      answer_idx: entry.ans,
      explanation: entry.exp ?? entry.explanation ?? null,
      passage: entry.passage ?? null,
      source_file: ctx.file,
    },
  ];
}

const files = readdirSync(sourceDir).filter((f) => f.endsWith('.json')).sort();
const report = {
  generated_at: new Date().toISOString(),
  source: sourceDir,
  files_total: files.length,
  files_imported: 0,
  files_placeholder_skipped: [],
  files_corrupt_skipped: [],
  questions_total: 0,
  questions_imported: 0,
  questions_with_explanations: 0,
  questions_deduped: 0,
  questions_invalid: [],
  by_exam: {},
  by_subject: {},
  notes: [
    'Placeholder files were skipped, not imported. Filling them is a separate syllabus-modelled authoring task (practice:true), never presented as verbatim official papers.',
    'Corrupt files were skipped. Repairing them needs the original papers; the importer does not guess at their contents.',
    'topic is NULL for every imported question until assigned by a syllabus-based authoring pass.',
  ],
};

const sqlLines = [
  '-- MyStudy v2 — question seed (generated by tools/import-questions/import.mjs).',
  '-- Source: ola1de/Exam-Questions-Data json/ (cloned 24 Nov 2026).',
  '-- Placeholders and corrupt files were skipped — see report.json.',
  '-- topic is NULL everywhere: assign topics in a syllabus-based authoring pass.',
  'BEGIN TRANSACTION;',
];
const seen = new Set();

for (const file of files) {
  const match = file.match(/^([A-Z]+)_(.+)_(\d{4})\.json$/);
  if (!match) {
    report.files_corrupt_skipped.push({ file, error: 'filename does not match <EXAM>_<Subject>_<Year>.json' });
    continue;
  }
  const [, exam, subject, yearStr] = match;
  const year = Number(yearStr);
  let raw;
  try {
    raw = readFileSync(join(sourceDir, file), 'utf8');
  } catch (err) {
    report.files_corrupt_skipped.push({ file, error: String(err) });
    continue;
  }
  let data;
  try {
    data = JSON.parse(raw);
  } catch (err) {
    report.files_corrupt_skipped.push({ file, error: `JSON parse error: ${err.message}` });
    continue;
  }
  if (!Array.isArray(data)) {
    report.files_corrupt_skipped.push({ file, error: 'top level is not an array' });
    continue;
  }
  // Placeholder file: a single question asking "Question Content Here?".
  if (data.length === 1 && data[0]?.q === PLACEHOLDER_Q) {
    report.files_placeholder_skipped.push(file);
    continue;
  }
  const ctx = { exam, subject, year, file };
  let importedFromFile = 0;
  for (const entry of data) {
    const items = normalise(entry, ctx);
    for (const item of items) {
      if (item.invalid) {
        report.questions_invalid.push({ file, reason: item.reason });
        continue;
      }
      report.questions_total += 1;
      const hash = contentHash(item);
      if (seen.has(hash)) {
        report.questions_deduped += 1;
        continue;
      }
      seen.add(hash);
      if (item.explanation) report.questions_with_explanations += 1;
      sqlLines.push(
        `INSERT OR IGNORE INTO questions (exam, subject, year, topic, q_text, options_json, answer_idx, explanation, passage, source_file, hash) VALUES (${sqlStr(item.exam)}, ${sqlStr(item.subject)}, ${item.year}, NULL, ${sqlStr(item.question)}, ${sqlStr(JSON.stringify(item.options))}, ${item.answer_idx}, ${sqlStr(item.explanation)}, ${sqlStr(item.passage)}, ${sqlStr(item.source_file)}, '${hash}');`,
      );
      importedFromFile += 1;
      report.questions_imported += 1;
      report.by_exam[exam] = (report.by_exam[exam] ?? 0) + 1;
      report.by_subject[subject] = (report.by_subject[subject] ?? 0) + 1;
    }
  }
  if (importedFromFile > 0) report.files_imported += 1;
}
sqlLines.push('COMMIT;');

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'report.json'), JSON.stringify(report, null, 2) + '\n');
writeFileSync(join(outDir, 'questions-seed.sql'), sqlLines.join('\n') + '\n');
writeFileSync(
  join(outDir, 'skipped.json'),
  JSON.stringify(
    {
      placeholders: report.files_placeholder_skipped,
      corrupt: report.files_corrupt_skipped,
    },
    null,
    2,
  ) + '\n',
);

console.log(`files: ${report.files_total} total, ${report.files_imported} imported, ${report.files_placeholder_skipped.length} placeholder-skipped, ${report.files_corrupt_skipped.length} corrupt-skipped`);
console.log(`questions: ${report.questions_total} seen, ${report.questions_imported} imported, ${report.questions_deduped} deduped, ${report.questions_with_explanations} with explanations`);
console.log(`wrote ${join(outDir, 'report.json')} and ${join(outDir, 'questions-seed.sql')}`);
